'use strict';
// Build-time only. The generated module has no Node or WASI imports.
const fs = require('node:fs'), path = require('node:path'), cp = require('node:child_process'), crypto = require('node:crypto');
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const wasiLibc = '574b88da481569b65a237cb80daf9a2d5aeaf82d';
function build(options = {}) {
    const compiler = options.compiler || process.env.WASI_CC;
    if (!compiler) throw Error('Set WASI_CC to the clang executable from wasi-sdk 25.');
    const compilerVersion = cp.execFileSync(compiler, ['--version'], { encoding: 'utf8' }).split('\n')[0];
    if (!compilerVersion.includes('19.1.5-wasi-sdk')) throw Error('The filter math build requires wasi-sdk 25 (clang 19.1.5).');
    const directory = options.buildDir || fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'rotorflight-math-'));
    fs.mkdirSync(directory, { recursive: true });
    const source = path.join(__dirname, 'portable_math.c'), wasmFile = path.join(directory, 'portable_math.wasm');
    const exports = ['sin', 'cos', 'tan', 'atan', 'atan2', 'pow', 'log', 'log2', 'log10', 'exp', 'sqrt'];
    const flags = ['-std=c11', '-O2', '-ffp-contract=off', '-fno-fast-math', '-mexec-model=reactor', source, '-lm',
        '-Wl,--strip-all', ...exports.map(name => '-Wl,--export=rf_' + name), '-o', wasmFile];
    cp.execFileSync(compiler, flags, { stdio: 'pipe' });
    const bytes = fs.readFileSync(wasmFile), compiled = new WebAssembly.Module(bytes);
    if (WebAssembly.Module.imports(compiled).length) throw Error('The filter math module must have no host imports.');
    const runtime = fs.readFileSync(path.join(__dirname, 'runtime.cjs'), 'utf8').replace(/\nmodule\.exports = \{ create \};\s*$/, '');
    const libc = cp.execFileSync(compiler, ['-print-file-name=libc.a'], { encoding: 'utf8' }).trim();
    const metadata = { sourceSha256: sha(fs.readFileSync(source)), runtimeSha256: sha(runtime), wasmSha256: sha(bytes), wasmBytes: bytes.length,
        compiler: compilerVersion, wasiSdk: 'wasi-sdk-25', wasiLibc,
        libcSha256: sha(fs.readFileSync(libc)),
        flags: flags.map(x => x === source ? 'portable_math.c' : x === wasmFile ? 'portable_math.wasm' : x),
        exports: WebAssembly.Module.exports(compiled).map(x => x.name) };
    const loader = `
function decode(text) {
    const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/', table = new Int16Array(128).fill(-1);
    for (let i = 0; i < alphabet.length; i++) table[alphabet.charCodeAt(i)] = i;
    const padding = text.endsWith('==') ? 2 : text.endsWith('=') ? 1 : 0, bytes = new Uint8Array(text.length / 4 * 3 - padding);
    let at = 0;
    for (let i = 0; i < text.length; i += 4) {
        const word = (table[text.charCodeAt(i)] << 18) | (table[text.charCodeAt(i + 1)] << 12) | ((table[text.charCodeAt(i + 2)] & 63) << 6) | (table[text.charCodeAt(i + 3)] & 63);
        for (let shift = 16; shift >= 0 && at < bytes.length; shift -= 8) bytes[at++] = (word >> shift) & 255;
    }
    return bytes;
}
module.exports = create(decode('${bytes.toString('base64')}'));
`;
    const output = options.output || path.join(__dirname, '../filter_math.cjs');
    fs.writeFileSync(output, '// Generated by math/build.cjs. Do not edit.\n// libm source and notices: math/README.md, math/LICENSES.txt.\n' + runtime + loader);
    fs.writeFileSync(path.join(__dirname, 'manifest.json'), JSON.stringify(metadata, null, 2) + '\n');
    return { output, ...metadata };
}
module.exports = { build };
if (require.main === module) console.log(JSON.stringify(build(), null, 2));
