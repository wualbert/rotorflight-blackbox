'use strict';
// Offline build from the complete, pinned upstream source archive. Requires
// CMake, a host C++17 compiler and Emscripten 4.0.18 (EMSDK or --emsdk PATH).
const fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const {spawnSync}=require('node:child_process'),{createHash}=require('node:crypto');
const arg=k=>process.argv.includes(k)?process.argv[process.argv.indexOf(k)+1]:null;
const sdk=arg('--emsdk')||process.env.EMSDK;
if(!sdk)throw Error('Supply --emsdk PATH for Emscripten 4.0.18.');
const compiler=path.resolve(sdk,'upstream/emscripten/em++');
const run=(cmd,args,cwd)=>{
    const r=spawnSync(cmd,args,{cwd,encoding:'utf8',stdio:'pipe',maxBuffer:32*1024*1024});
    if(r.status!==0)throw Error([cmd,...args].join(' ')+'\n'+(r.error||r.stderr||r.stdout));
    return r.stdout;
};
if(!/4\.0\.18/.test(run(compiler,['--version'])))throw Error('This build requires Emscripten 4.0.18.');
const sha=f=>createHash('sha256').update(fs.readFileSync(f)).digest('hex');
const archive=path.join(__dirname,'nomad-4.5.1.tar.gz');
if(sha(archive)!=='ce5db6f0db0a410fd80ed251557272472a49efd911274d8a52959f24ed95368c')throw Error('Upstream source archive hash mismatch.');
const work=fs.mkdtempSync(path.join(os.tmpdir(),'rotorflight-nomad-'));
console.log('Build directory: '+work);
run('tar',['-xzf',archive,'-C',work]);
const source=path.join(work,'nomad-v.4.5.1'),build=path.join(work,'build');
const attributes=path.join(source,'src/Attribute'),generator=path.join(work,'attributes');
run(process.env.CXX||'c++',['-std=c++17',path.join(attributes,'WriteAttributeDefinitionFile.cpp'),'-o',generator]);
run(generator,[],attributes);
// The upstream build runs a host generator. Generate its headers above, then
// omit that executable during cross-compilation. No algorithm source changes.
const cmakeFile=path.join(source,'src/CMakeLists.txt'),cmake=fs.readFileSync(cmakeFile,'utf8');
const start=cmake.indexOf('# Build attribute executable'),end=cmake.indexOf('# Build libraries and executable',start);
if(start<0||end<start)throw Error('Upstream CMake generator block changed.');
fs.writeFileSync(cmakeFile,cmake.slice(0,start)+'# Attribute headers generated by the host compiler.\n\n'+cmake.slice(end));
run(path.resolve(sdk,'upstream/emscripten/emcmake'),['cmake','-S',source,'-B',build,
    '-DTEST_OPENMP=OFF','-DBUILD_EXAMPLES=OFF','-DBUILD_INTERFACE_C=OFF','-DCMAKE_CXX_FLAGS=-fexceptions','-DUSE_SGTELIB=ON']);
run('cmake',['--build',build,'--target','nomadAlgos','--parallel',arg('--jobs')||'4']);
const output=path.resolve(arg('--output')||path.join(__dirname,'nomad.cjs'));
const libraries=['src/libnomadAlgos.a','src/libnomadEval.a','src/libnomadUtils.a','ext/sgtelib/libsgtelib.a'];
// Library locations are checked explicitly: never silently link system NOMAD.
for(const lib of libraries)if(!fs.existsSync(path.join(build,lib)))throw Error('Missing upstream library: '+lib);
run(compiler,['-O3','-std=c++17','-fexceptions','-I'+path.join(source,'src'),'-I'+path.join(source,'ext/sgtelib/src'),'-DUSE_SGTELIB',
    path.join(__dirname,'bridge.cpp'),...libraries.map(lib=>path.join(build,lib)),
    '--no-entry','--post-js',path.join(__dirname,'exports.js'),'-sMODULARIZE=0','-sWASM_ASYNC_COMPILATION=0','-sSINGLE_FILE=1',
    '-sALLOW_MEMORY_GROWTH=1','-sENVIRONMENT=web,worker,node','-sMIN_CHROME_VERSION=99',
    '-sEXPORTED_FUNCTIONS=["_rf_nomad_optimize","_rf_nomad_message","_malloc","_free"]',
    '-sEXPORTED_RUNTIME_METHODS=["UTF8ToString","stringToUTF8","lengthBytesUTF8"]','-o',output]);
console.log(JSON.stringify({output,sha256:sha(output),upstream:'NOMAD 4.5.1',emscripten:'4.0.18',work},null,2));
