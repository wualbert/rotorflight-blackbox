'use strict';
// Rebuild the portable f64 kernel with a pinned LLVM floating-point contract.
const fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process'),crypto=require('node:crypto');
const sha=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
function build(options={}) {
    const compiler=options.compiler||process.env.WASI_CC;
    if(!compiler)throw Error('Set WASI_CC to the clang executable from wasi-sdk 25.');
    const compilerVersion=cp.execFileSync(compiler,['--version'],{encoding:'utf8'}).split('\n')[0];
    if(!compilerVersion.includes('19.1.5-wasi-sdk'))throw Error('The reconstruction build requires wasi-sdk 25 (clang 19.1.5).');
    const directory=options.buildDir||fs.mkdtempSync(path.join(require('node:os').tmpdir(),'rotorflight-reconstruct-'));
    fs.mkdirSync(directory,{recursive:true});
    const wasmFile=path.join(directory,'kernel.wasm'),output=options.output||path.join(__dirname,'../filter_solve.cjs');
    const source=path.join(__dirname,'kernel.c');
    const flags=['-std=c11','-O2','-ffp-contract=off','-fno-fast-math','-mexec-model=reactor',source,'-lm',
        '-Wl,--export=malloc','-Wl,--export=free','-Wl,--export=rf_solve','-Wl,--max-memory=1073741824','-Wl,--strip-all','-o',wasmFile];
    cp.execFileSync(compiler,flags,{stdio:'pipe'});
    const bytes=fs.readFileSync(wasmFile),module=new WebAssembly.Module(bytes);
    if(WebAssembly.Module.imports(module).length)throw Error('The reconstruction kernel must have no host imports.');
    const runtime=fs.readFileSync(path.join(__dirname,'runtime.cjs'),'utf8').replace(/\nmodule\.exports=\{create\};\s*$/,'');
    const metadata={sourceSha256:sha(fs.readFileSync(source)),runtimeSha256:sha(runtime),wasmSha256:sha(bytes),wasmBytes:bytes.length,
        compiler:compilerVersion,
        flags:flags.map(x=>x===source?'kernel.c':x===wasmFile?'kernel.wasm':x),exports:WebAssembly.Module.exports(module).map(x=>x.name)};
    const prelude=`// Generated by reconstruct/build.cjs. Do not edit.\n// WebAssembly SHA-256: ${metadata.wasmSha256}\n`;
    const loader=`\nfunction decode(text) {
    const alphabet='ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/',table=new Int16Array(128).fill(-1);
    for(let i=0;i<alphabet.length;i++)table[alphabet.charCodeAt(i)]=i;
    const padding=text.endsWith('==')?2:text.endsWith('=')?1:0,bytes=new Uint8Array(text.length/4*3-padding);
    let at=0;
    for(let i=0;i<text.length;i+=4){const word=(table[text.charCodeAt(i)]<<18)|(table[text.charCodeAt(i+1)]<<12)|((table[text.charCodeAt(i+2)]&63)<<6)|(table[text.charCodeAt(i+3)]&63);for(let shift=16;shift>=0&&at<bytes.length;shift-=8)bytes[at++]=(word>>shift)&255;}
    return bytes;
}
const kernel=create(decode('${bytes.toString('base64')}'));
module.exports={solve:options=>kernel.solve(options),wasmSha256:'${metadata.wasmSha256}'};
`;
    fs.writeFileSync(output,prelude+runtime+loader);
    fs.writeFileSync(path.join(__dirname,'manifest.json'),JSON.stringify(metadata,null,2)+'\n');
    return {output,...metadata};
}
module.exports={build};
if(require.main===module)console.log(JSON.stringify(build(),null,2));
